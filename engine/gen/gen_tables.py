"""Generates the data tables the app reads from Epson's files:
- es_hrd_tables.h: the V550's hardware tables (EPSON Scan ES00EB HRD): Unsharp Mask, clipping, grain,
  descreening, resolution, DIGITAL ICE resolution and Dust Removal records
- es_pdf_tables.h: PDFLib's JPEG quantization tables (CJpegAPI::Open pointer arrays)"""
import os
import struct
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hrd  # noqa: E402


def rows(recs, fields):
    return ', '.join('{ ' + ', '.join(str(r[i]) for i in fields) + ' }' for r in recs)


def hrd_header(hrd_path, out):
    H = hrd.parse(hrd_path)[0]
    usm = H['usm']
    crp = H['clip_rev_parm'][0]
    noise = H['usm_noise'][0][3]
    L = ['/* Generated by the builder from EPSON Scan ES00EB HRD (the V550 hardware file). */',
         'typedef struct { uint32_t max_res, strength, radius, clipping; } UsmRow;',
         'static const UsmRow kUsmReflective[] = { %s };' % rows(usm[0], (0, 1, 2, 3)),
         'static const UsmRow kUsmTable3[] = { %s };' % rows(usm[3], (0, 1, 2, 3)),
         'static const UsmRow kUsmTable4[] = { %s };' % rows(usm[4], (0, 1, 2, 3)),
         'static const int kClipCtl = %d, kClipRev = %d;' % (H['clip_ctl'][0][0][0], H['clip_rev'][0][0][0]),
         'static const int kClipRevParm[6] = { %s };' % ', '.join(
             str(r[0] | (r[1] << 16)) + ', ' + str(r[2] | (r[3] << 16)) for r in crp),
         'static const uint16_t kUsmNoise3[4] = { %s };' % ', '.join(str(v) for v in noise),
         'static const uint16_t kUsmBlur = %d;' % H['usm_blur'][0][0][0],
         'typedef struct { uint32_t max_res, value; } GrainRow;',
         'static const GrainRow kGrain[3][%d] = { %s };' % (len(H['grain'][0]), ', '.join(
             '{ ' + rows(t, (0, 1)) + ' }' for t in H['grain'])),
         'typedef struct { uint32_t max_res, scan_res, value; } MoireRow;']
    for i, t in enumerate(H['descreening']):
        L.append('static const MoireRow kMoire%d[] = { %s };' % (i, rows(t, (0, 1, 2))))
    L.append('typedef struct { uint32_t max_res, scan_res; } ResRow;')
    res = H['resolution']
    for name, idx in (('kResFbX', 0), ('kResFbY', 1), ('kResTpuX', 18), ('kResTpuY', 19)):
        L.append('static const ResRow %s[] = { %s };' % (name, rows(res[idx], (0, 1))))
    L.append('static const ResRow kResIce[] = { %s };' % rows(H['dice_res'][2], (0, 1)))
    L.append('static const int kDust[3][3][8] = { %s };' % ', '.join(
        '{ ' + ', '.join('{ ' + ', '.join(str(v) for v in r) + ' }' for r in t) + ' }' for t in H['dust']))
    open(out, 'w').write('\n'.join(L) + '\n')


def macho_sections(d):
    """(vmaddr, fileoff, size) of every section of a thin i386 Mach-O"""
    ncmds = struct.unpack('<I', d[16:20])[0]
    o = 28
    out = []
    for _ in range(ncmds):
        cmd, size = struct.unpack('<II', d[o:o + 8])
        if cmd == 1:                          # LC_SEGMENT
            nsect = struct.unpack('<I', d[o + 48:o + 52])[0]
            for s in range(nsect):
                q = o + 56 + s * 68
                addr, sz, off = struct.unpack('<III', d[q + 32:q + 44])
                out.append((addr, off, sz))
        o += size
    return out


def vread(d, secs, addr, n):
    for a, off, sz in secs:
        if a <= addr < a + sz and off:
            return d[off + addr - a:off + addr - a + n]
    raise ValueError('address %x not in the file' % addr)


def pdf_header(pdflib_i386, out):
    d = open(pdflib_i386, 'rb').read()
    secs = macho_sections(d)
    L = ['/* Generated by the builder from PDFLib (CJpegCoder quantization tables, natural order). */']
    for name, arr in (('kEpPdf_luma', 0x85060), ('kEpPdf_chroma', 0x85020)):
        ptrs = struct.unpack('<10I', vread(d, secs, arr, 40))
        L.append('static const unsigned short %s[10][64] = {' % name)
        for p in ptrs:
            v = struct.unpack('<64H', vread(d, secs, p, 128))
            L.append('    {' + ','.join(str(x) for x in v) + '},')
        L.append('};')
    open(out, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    hrd_header(sys.argv[1], sys.argv[3] + '/es_hrd_tables.h')
    pdf_header(sys.argv[2], sys.argv[3] + '/es_pdf_tables.h')
