"""Epson's UI sentences the app shows (alerts, notices) come from the installer's STR# resources at
build time: es_strings.h defines one ESS_ macro per sentence, made by the rules in strings.json."""
import json
import os
import struct
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import macres  # noqa: E402

DS = 'Library/Image Capture/TWAIN Data Sources/EPSON Perfection V550.ds/Contents/PlugIns/'


def string_lists(payload, files):
    """{tag: {id: [strings]}} for the resource files named in the recipe"""
    out = {}
    for tag, rel in files.items():
        r = macres.open_rsrc(os.path.join(payload, rel))
        lists = {}
        for rid, res in r[b'STR#'].items():
            d = res.data
            n = struct.unpack('>h', d[:2])[0]
            o, items = 2, []
            for _ in range(n):
                ln = d[o]
                items.append(d[o + 1:o + 1 + ln].decode('mac_roman'))
                o += 1 + ln
            lists[rid] = items
        out[tag] = lists
    return out


def transform(raw, spec):
    """the Epson sentence, the way the app shows it"""
    parts = raw.split('\r')
    if spec.get('lines'):
        parts = parts[:spec['lines']]
    if spec.get('rstrip'):
        parts = [p.rstrip() for p in parts]
    text = spec.get('nl', '\n').join(parts)
    if spec.get('fmt'):
        text = text.replace('%s', '%@')
    return text


def objc_literal(text):
    esc = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    return '@"' + esc + '"'


def generate(payload, recipe_path, out_path):
    recipe = json.load(open(recipe_path))
    lists = string_lists(payload, recipe['files'])
    lines = ['/* Generated by the builder from the Epson installer\'s string resources. */']
    for m in recipe['strings']:
        raw = lists[m['tag']][m['id']][m['index'] - 1]
        lines.append('#define %s %s' % (m['macro'], objc_literal(transform(raw, m))))
    open(out_path, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    generate(sys.argv[1], sys.argv[2], sys.argv[3])
